#!/usr/bin/env python3
"""Compile the editable bank catalogue; no runtime dictionary is required."""
import argparse
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if the generated header is stale')
args = parser.parse_args()
catalogue = json.loads((root / 'banks/catalogue.json').read_text())
engine = (root / 'lib/SpeakJet/src/speakjet.c').read_text()
block = re.search(r'static const char \*const names\[\]\s*=\s*\{\s*("IY".*?)\};', engine, re.S)
assert block, 'Native SpeakJet mnemonic table not found'
names = re.findall(r'"([A-Z0-9_]+)"', block[1])
assert len(names) == 127
codes = {name: index + 128 for index, name in enumerate(names)}
codes.update({f'P{i}': i for i in range(7)})
assert catalogue['format'] == 1
assert all('entries' in b for b in catalogue['banks'][:7])
assert all('native' in b for b in catalogue['banks'][7:])
assert [b['id'] for b in catalogue['banks']] == list(range(14))
lines = ['#pragma once', '// Generated by scripts/generate_banks.py from banks/catalogue.json.',
         '// CMU-derived entries: see banks/CMUDICT-LICENSE and banks/README.md.', '']
assert [b.get('role') for b in catalogue['banks']].count('numbers') == 1
number_entries = next(b['entries'] for b in catalogue['banks'] if b.get('role') == 'numbers')
assert [e['label'] for e in number_entries[:10]] == 'ZERO ONE TWO THREE FOUR FIVE SIX SEVEN EIGHT NINE'.split()
expressions = []
total = longest = 0
for bank in catalogue['banks']:
    number = bank['id']
    if 'native' in bank:
        first, last = bank['native']
        assert (bank['name'], first, last) == [('Vowels',128,139), ('Voiced',128,181), ('Voiced Stop',170,181), ('Voiceless',182,199), ('All',128,199), ('All Effects',200,254), ('DTMF',240,251)][number-7]
        expressions.append(f'nativeBank({first}, {last})')
        total += last - first + 1
        continue
    assert number < 7, 'The seven Emy groups must follow the curated banks'
    entries = bank['entries']
    assert len(entries) == 16, bank['name']
    assert len({e['label'] for e in entries}) == 16
    for index, entry in enumerate(entries):
        assert bool('bytes' in entry) != bool('phonemes' in entry)
        data = entry.get('bytes') if 'bytes' in entry else [codes[t] for t in entry['phonemes']]
        assert 0 < len(data) <= 64, entry['label']
        assert all(isinstance(value, int) and 0 <= value <= 254 for value in data)
        assert entry['label'].isascii() and '\n' not in entry['label']
        longest = max(longest, len(data))
        lines.append(f'constexpr uint8_t bank{number}Item{index}[] = {{{", ".join(map(str, data))}}};')
    table = 'spokenDigits' if bank.get('role') == 'numbers' else f'bank{number}Entries'
    lines.append(f'constexpr Entry {table}[] = {{')
    for index, entry in enumerate(entries):
        lines.append(f'    phrase({json.dumps(entry["label"])}, bank{number}Item{index}),')
    lines += ['};', '']
    expressions.append(f'bank({table})')
    total += len(entries)
lines += ['constexpr Bank banks[] = {']
lines += [f'    {expr}, // {b["id"]}: {b["name"]}' for expr, b in zip(expressions, catalogue['banks'])]
lines += ['};', 'constexpr int BankCount = sizeof(banks) / sizeof(banks[0]);',
          'static_assert(BankCount == 14, "Seven curated banks followed by seven Emy banks");',
          'constexpr const char *BankNames[] = {']
lines += [f'    {json.dumps(b["name"])},' for b in catalogue['banks']]
lines += ['};', '']
text = '\n'.join(lines)
target = root / 'src/banks_generated.h'
if args.check:
    assert target.read_text() == text, 'Run python3 scripts/generate_banks.py'
else:
    target.write_text(text)
print(f'14 banks, {total} selections, 16 entries per curated bank; longest entry {longest}/64 bytes')
